    @And("^User verifies data is populated in the \"(?:Last Updated By|Last updated by)\" column$")
    public void userVerifiesDataIsPopulatedInTheLastUpdatedByColumn(DataTable table) {
        String cellData = documentCountPageObject.getLastUpdatedByColumnData();
        Assert.assertNotNull("Regression Failure: The data cell was completely null!", cellData);
        Assert.assertFalse("Regression Failure: The filtered row returned an empty cell!", cellData.trim().isEmpty());

        String expectedEmail = null;
        if (table != null) {
            List<Map<String, String>> data = table.asMaps(String.class, String.class);
            if (data != null && !data.isEmpty()) {
                expectedEmail = data.get(0).get("value");
            }
        }

        if (expectedEmail != null && !expectedEmail.trim().isEmpty()) {
            // Specific validation if provided in the test step's DataTable
            Assert.assertEquals("Regression Failure: Last Updated By cell value mismatch!", expectedEmail.trim(), cellData.trim());
            log.info("Successfully verified specific email in column (via DataTable): {}", cellData);
        } else {
            // Generic validation (format check) if no specific value is provided
            Assert.assertTrue("Regression Failure: The populated data '" + cellData + "' does not look like a valid email address!",
                    cellData.contains("@") && (cellData.contains(".com") || cellData.contains(".org") || cellData.contains(".net")));
            log.info("Successfully verified generic email data format in column: {}", cellData);
        }
    }

